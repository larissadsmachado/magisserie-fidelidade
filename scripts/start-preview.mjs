import { spawn } from "node:child_process";
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadEnv } from "vite";
import { projectRoot } from "./sites-env.mjs";

const root = projectRoot;
const configPath = path.join(root, "dist", "server", "wrangler.json");
const devVarsPath = path.join(path.dirname(configPath), ".dev.vars");
const generatedMarker = "# generated by scripts/start-preview.mjs";

if (!existsSync(configPath)) {
  throw new Error("Build the Worker first by running `pnpm build`.");
}
if (
  existsSync(devVarsPath) &&
  readFileSync(devVarsPath, "utf8").split(/\r?\n/, 1)[0] !== generatedMarker
) {
  throw new Error(
    "Remove the existing dist/server/.dev.vars before starting the local preview.",
  );
}

const fileEnv = loadEnv("development", root, "");
const adminPassword = process.env.ADMIN_PASSWORD ?? fileEnv.ADMIN_PASSWORD;
const authSecret = process.env.AUTH_SECRET ?? fileEnv.AUTH_SECRET;
if (!adminPassword || !authSecret) {
  throw new Error(
    "Set ADMIN_PASSWORD and AUTH_SECRET in the project-root .env before running `pnpm start`.",
  );
}

function encodeEnvValue(value) {
  if (/[\r\n]/.test(value)) {
    throw new Error("Local authentication secrets cannot contain line breaks.");
  }
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

writeFileSync(
  devVarsPath,
  `${generatedMarker}\nADMIN_PASSWORD=${encodeEnvValue(adminPassword)}\nAUTH_SECRET=${encodeEnvValue(authSecret)}\n`,
  { mode: 0o600 },
);

const child = spawn(
  process.execPath,
  [
    "--import",
    new URL("./sites-env.mjs", import.meta.url).href,
    fileURLToPath(new URL("../node_modules/wrangler/bin/wrangler.js", import.meta.url)),
    "dev",
    "--config",
    configPath,
    "--local",
    "--persist-to",
    ".wrangler/state",
    "--ip",
    "127.0.0.1",
    "--inspector-port",
    "0",
    ...process.argv.slice(2),
  ],
  { cwd: root, stdio: "inherit" },
);

let stopping = false;
for (const signal of ["SIGINT", "SIGTERM"]) {
  process.on(signal, () => {
    if (stopping) return;
    stopping = true;
    child.kill(signal);
  });
}

try {
  const exitCode = await new Promise((resolve, reject) => {
    child.once("error", reject);
    child.once("exit", (code) => resolve(code ?? 1));
  });
  process.exitCode = exitCode;
} finally {
  if (existsSync(devVarsPath)) unlinkSync(devVarsPath);
}
